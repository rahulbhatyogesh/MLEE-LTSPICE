"""Render a :class:`CircuitGraph` as a SPICE netlist."""

from __future__ import annotations

from .classes import MODEL_CARDS, SYMBOL_LIBS, spec
from .graph import CircuitGraph

DEFAULT_ANALYSIS = ".op"


def _element_line(graph: CircuitGraph, comp) -> str | None:
    sp = spec(comp.cls)
    nodes = [graph.node_name(n) if n >= 0 else "NC" for n in comp.nodes]
    ref, val = comp.ref, comp.value

    if sp.spice_prefix in ("R", "C", "L"):
        return f"{ref} {nodes[0]} {nodes[1]} {val}"
    if sp.spice_prefix == "V":
        return f"{ref} {nodes[0]} {nodes[1]} DC {val}"
    if sp.spice_prefix == "I":
        return f"{ref} {nodes[0]} {nodes[1]} DC {val}"
    if sp.spice_prefix == "D":
        return f"{ref} {nodes[0]} {nodes[1]} {val}"
    if sp.spice_prefix == "Q":
        return f"{ref} {nodes[0]} {nodes[1]} {nodes[2]} {val}"
    if sp.spice_prefix == "M":
        # MOSFETs take D G S B; tie bulk to source.
        return f"{ref} {nodes[0]} {nodes[1]} {nodes[2]} {nodes[2]} {val}"
    if sp.spice_prefix == "S":
        return f"{ref} {nodes[0]} {nodes[1]} 0 0 {val}"
    if sp.spice_prefix == "X":
        return f"{ref} {' '.join(nodes)} {val}"
    return None


def directives(graph: CircuitGraph) -> list[str]:
    """``.model`` / ``.lib`` lines needed by the components actually present."""
    out: list[str] = []
    seen: set = set()
    for c in graph.components:
        sp = spec(c.cls)
        if c.value in MODEL_CARDS and c.value not in seen:
            out.append(MODEL_CARDS[c.value])
            seen.add(c.value)
        lib = SYMBOL_LIBS.get(sp.ltspice_symbol or "")
        if lib and lib not in seen:
            out.append(f".lib {lib}")
            seen.add(lib)
    return out


def to_netlist(
    graph: CircuitGraph,
    *,
    title: str = "circuit2spice",
    analysis: str = DEFAULT_ANALYSIS,
) -> str:
    """Build a self-contained SPICE deck."""
    lines = [f"* {title}", "* Generated by circuit2spice from a hand-drawn schematic"]
    for w in graph.warnings:
        lines.append(f"* WARNING: {w}")
    lines.append("")
    for comp in graph.components:
        line = _element_line(graph, comp)
        if line:
            lines.append(line)
    lines.append("")
    lines.extend(directives(graph))
    lines.append(analysis)
    lines.append(".end")
    return "\n".join(lines) + "\n"
